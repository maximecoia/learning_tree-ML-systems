#include "libft.h"

/*
 * Frees every element of *lst and its content, then sets *lst to NULL.
 * Edge:    lst or del NULL: frees nothing, the list stays as it was.
 */
void	ft_lstclear(t_list **lst, void (*del)(void *))
{
	t_list	*next;

	if (!lst || !del)
		return ;
	while (*lst)
	{
		next = (*lst)->next;
		ft_lstdelone(*lst, del);
		*lst = next;
	}
}
