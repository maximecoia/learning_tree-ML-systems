#include "libft.h"

/*
 * Copies s into a new string where character k becomes f(k, s[k]).
 * Returns: the new string, or NULL if s or f is NULL or malloc fails.
 * Edge:    s is unchanged.
 */
char	*ft_strmapi(char const *s, char (*f)(unsigned int, char))
{
	char			*result;
	unsigned int	i;

	if (!s || !f)
		return (NULL);
	result = ft_strdup(s);
	if (!result)
		return (NULL);
	i = 0;
	while (result[i])
	{
		result[i] = f(i, result[i]);
		i++;
	}
	return (result);
}
