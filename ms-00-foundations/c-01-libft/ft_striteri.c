#include "libft.h"

/*
 * Calls f(k, &s[k]) on each character of s: f may change it in place.
 * Returns: nothing. Allocates nothing.
 * Edge:    s or f NULL: does nothing.
 */
void	ft_striteri(char *s, void (*f)(unsigned int, char *))
{
	unsigned int	i;

	if (!s || !f)
		return ;
	i = 0;
	while (s[i])
	{
		f(i, s + i);
		i++;
	}
}
