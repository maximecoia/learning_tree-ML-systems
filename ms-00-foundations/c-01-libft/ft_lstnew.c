#include "libft.h"

/*
 * Allocates a new element: content = content, next = NULL.
 * Returns: the element, or NULL when malloc fails.
 * Edge:    content is stored as is, not copied.
 */
t_list	*ft_lstnew(void *content)
{
	t_list	*node;

	node = malloc(sizeof(t_list));
	if (!node)
		return (NULL);
	node->content = content;
	node->next = NULL;
	return (node);
}
