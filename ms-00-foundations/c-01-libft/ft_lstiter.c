#include "libft.h"

/*
 * Calls f on the content of each element, from head to tail.
 * Edge:    f NULL: does nothing.
 */
void	ft_lstiter(t_list *lst, void (*f)(void *))
{
	if (!f)
		return ;
	while (lst)
	{
		f(lst->content);
		lst = lst->next;
	}
}
