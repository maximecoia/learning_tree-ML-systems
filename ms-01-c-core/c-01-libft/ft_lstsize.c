#include "libft.h"

/*
 * Counts the elements of the list lst.
 * Returns: that count, 0 for an empty list.
 */
unsigned int	ft_lstsize(t_list *lst)
{
	unsigned int	count;

	count = 0;
	while (lst)
	{
		count++;
		lst = lst->next;
	}
	return (count);
}
