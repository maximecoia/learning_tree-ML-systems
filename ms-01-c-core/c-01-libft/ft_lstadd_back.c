#include "libft.h"

/*
 * Puts new at the end of the list *lst.
 * Edge:    empty list, *lst NULL: new becomes the head.
 *          lst or new NULL: does nothing.
 */
void	ft_lstadd_back(t_list **lst, t_list *new)
{
	t_list	*last;

	if (!lst || !new)
		return ;
	if (!*lst)
	{
		*lst = new;
		return ;
	}
	last = ft_lstlast(*lst);
	last->next = new;
}
