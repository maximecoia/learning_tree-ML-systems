def moyenne_de_deux(a, b): 
    return (a + b) / 2

def division_entiere(a, b): 
    return a // b

def reste(a, b): return a % b

def puissance(base, exposant): 
    return base ** exposant

def ecart(a, b): 
    return abs(a - b)

def pourcentage(partie, total): 
    return round(partie / total * 100, 2)